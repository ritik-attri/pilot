"""Generate the long-horizon scenarios and the longer window sweeps.

    python -m eval.longgen [--out DIR]

Why: almost every hand-written scenario fits inside b0's recency window (own_02's 13k-token
paste is the exception, and it fails b0 for another reason). b0's real replies are
short (about 70 tokens on average in the baseline run), so even sweep_40's whole history
still reaches its probe and b0 sees the planted fact. The brief's complaint is "gets less
useful the more they use it", which only shows once a fact is weeks of work behind the
question. These files replay six weeks of daily work from a written pool of messages and
plant one fact early in it.

Inputs (all in the repository; nothing here calls an API):
  scenarios/long/_pool/pool_*.json       messages {day 1..30, time, account, kind, text};
                                         workday 1 is Mon 2 Feb 2026, day 30 is Fri 13 Mar
  scenarios/long/_pool/heavy_day.json    one day of back-to-back calls (Tue 10 Feb 2026)
  scenarios/sweep/sweep_40.jsonl         the longest hand-written sweep
  results/runs/baseline/events/b0__*.jsonl   b0's real replies, for the window estimate

Outputs: scenarios/long/long_*.jsonl and scenarios/sweep/sweep_080|160|320.jsonl, plus this
generator's entries in scenarios/needles.json, eval/audit_controls.jsonl and
scenarios/INDEX.md. Re-running replaces those entries and keeps everyone else's.

The rules. There is no randomness anywhere, so the same inputs always give the same bytes.
  * Sessions. Within a day, a message joins the current session while it comes at most 25
    minutes after the previous one and the session has fewer than 4 messages. A session is
    start (1 minute before its first message), the messages, then end (2 minutes after the
    last), except that every 4th session has no end: the user closed the tab. A restart
    separates days.
  * Time only moves forward. An event that would not come after the previous one (two
    messages in the same minute, say) moves to one minute after it.
  * A needle is its own session at its day and time, moved 5 minutes later until it
    overlaps no other session.
"""


# ---------------------------------------------------------------- dates and files


def next_workday(day: date) -> date:
    """The first Monday-to-Friday date after `day`."""
    day += timedelta(days=1)
    while day.weekday() >= 5:  # Saturday or Sunday
        day += timedelta(days=1)
    return day


def workday(first: date, n: int) -> date:
    """Workday number n (1-based) of a run of workdays that starts on `first`."""
    day = first
    for _ in range(n - 1):
        day = next_workday(day)
    return day


def at(day: date, hhmm: str) -> datetime:
    """`day` at the time "HH:MM"."""
    return datetime.combine(day, time.fromisoformat(hhmm))


def sweep_stem(size: int) -> str:
    return f"sweep_{size:03d}"


def own_stems() -> set[str]:
    """Stems of every scenario this generator writes: its needles and audit rows are its own."""
    return {spec.stem for spec in LONG_SCENARIOS} | {sweep_stem(size) for size in SWEEP_SIZES}


def scenario_paths() -> list[Path]:
    """Repository-relative paths of every scenario file this generator writes."""
    return [LONG_DIR / f"{spec.stem}.jsonl" for spec in LONG_SCENARIOS] + [
        SWEEP_DIR / f"{sweep_stem(size)}.jsonl" for size in SWEEP_SIZES
    ]


def load_pool(root: Path) -> list[dict]:
    """Every pool_*.json message, sorted by (day, time, account). The sort is stable, so
    messages that tie on all three keep their file order."""
    messages: list[dict] = []
    for path in sorted((root / POOL_DIR).glob("pool_*.json")):
        with open(path, encoding="utf-8") as f:
            messages += json.load(f)
    return sorted(messages, key=lambda m: (m["day"], time.fromisoformat(m["time"]), m["account"]))


def load_heavy_day(root: Path) -> list[dict]:
    """heavy_day.json in time order."""
    with open(root / POOL_DIR / "heavy_day.json", encoding="utf-8") as f:
        return sorted(json.load(f), key=lambda m: time.fromisoformat(m["time"]))


def check_pool(pool: list[dict]) -> None:
    """Stop if the pool mentions anything a scenario plants or asks about."""
    text = "\n".join(m["text"] for m in pool).lower()
    found = [name for name in PLANTED if name.lower() in text]
    if found:
        raise ValueError(f"the pool mentions planted names, so a probe would be ambiguous: {', '.join(found)}")


def read_text(path: Path) -> tuple[str, str]:
    """A text file with "\\n" line endings, plus the line ending the file uses on disk. The
    file is written back with its own line endings, so only our entries change."""
    with open(path, encoding="utf-8", newline="") as f:
        raw = f.read()
    return raw.replace("\r\n", "\n"), ("\r\n" if "\r\n" in raw else "\n")


def to_line(row: dict) -> str:
    """One compact JSON line: the format of the brief's samples."""
    return json.dumps(row, ensure_ascii=False, separators=(",", ":"))


# ---------------------------------------------------------------- sessions and events


def pool_turns(messages: list[dict], first_day: date) -> list[Turn]:
    """Pool messages as turns, their workday `day` counted from `first_day`."""
    return [Turn(at(workday(first_day, m["day"]), m["time"]), m["text"]) for m in messages]


def group_sessions(turns: list[Turn]) -> list[list[Turn]]:
    """Split turns (in time order) into sessions. A turn joins the current session when it
    is on the same day, at most 25 minutes after the session's last turn, and the session
    has fewer than 4 turns; otherwise it opens a new session."""
    sessions: list[list[Turn]] = []
    for turn in turns:
        current = sessions[-1] if sessions else []
        joins = (
            0 < len(current) < SESSION_MAX
            and turn.when.date() == current[-1].when.date()
            and turn.when - current[-1].when <= SESSION_GAP
        )
        if joins:
            current.append(turn)
        else:
            sessions.append([turn])
    return sessions


def collides(when: datetime, sessions: list[list[Turn]]) -> bool:
    """Would a one-message session at `when` (start 1 minute before, end 2 minutes after)
    touch or overlap one of `sessions` (each from 1 minute before its first turn to 2
    minutes after its last)?"""
    for session in sessions:
        start, end = session[0].when - MINUTE, session[-1].when + 2 * MINUTE
        if when - MINUTE <= end and start <= when + 2 * MINUTE:
            return True
    return False


def place_needle(when: datetime, sessions: list[list[Turn]]) -> datetime:
    """The needle's time, moved 5 minutes later until its session overlaps no other."""
    while collides(when, sessions):
        when += NEEDLE_STEP
    return when


def event(kind: str, session: str, ts: datetime, text: str | None = None, expect: dict | None = None) -> dict:
    """One scenario event, its keys in the order the samples use."""
    row = {"type": kind, "user": USER, "session": session, "ts": ts.isoformat(timespec="seconds")}
    if text is not None:
        row["text"] = text
    if expect is not None:
        row["expect"] = expect
    return row


def later(wanted: datetime, last: datetime | None) -> datetime:
    """`wanted`, or one minute after `last` when `wanted` is not after it."""
    if last is None or wanted > last:
        return wanted
    return last + MINUTE


def lay_out(sessions: list[list[Turn]], first_number: int, width: int) -> list[dict]:
    """Events for sessions in time order, numbered from `first_number` ("s" + number,
    zero-padded to `width` digits).

    Each session is start (1 minute before its first turn), its turns, and end (2 minutes
    after its last turn); every 4th session by number has no end, but the minute is still
    used up, so dropping it never moves another event. A restart separates days.
    """
    events: list[dict] = []
    last: datetime | None = None  # time of the previous event (or of the end nobody sent)
    for number, session in enumerate(sessions, start=first_number):
        session_id = f"s{number:0{width}d}"
        if last is not None and session[0].when.date() != last.date():
            events.append({"type": "restart"})  # the harness rebuilds the assistant between days
        last = later(session[0].when - MINUTE, last)
        events.append(event("start", session_id, last))
        for turn in session:
            last = later(turn.when, last)
            kind = "probe" if turn.expect else "msg"
            events.append(event(kind, session_id, last, turn.text, turn.expect))
        last += 2 * MINUTE
        if number % NO_END_EVERY != 0:
            events.append(event("end", session_id, last))
    return events


def largest_move(sessions: list[list[Turn]], events: list[dict]) -> int:
    """The most minutes lay_out moved a turn from its planned time to keep time moving forward."""
    planned = [turn.when for session in sessions for turn in session]
    laid_out = [datetime.fromisoformat(e["ts"]) for e in events if e["type"] in ("msg", "probe")]
    return max(int((actual - wanted).total_seconds()) // 60 for wanted, actual in zip(planned, laid_out))


# ---------------------------------------------------------------- the scenarios


def build_long(spec: LongScenario, pool: list[dict], heavy: list[dict]) -> tuple[list[dict], int]:
    """Events of one long scenario (its source messages as sessions, the needle sessions
    slotted into gaps between them, the probe session last) and the largest move."""
    if spec.heavy_day:
        turns = [Turn(at(HEAVY_DAY, m["time"]), m["text"]) for m in heavy]
        probe_day = HEAVY_DAY
    else:
        turns = pool_turns(pool, POOL_DAY_1)
        probe_day = PROBE_DAY
    sessions = group_sessions(turns)
    for day, hhmm, text in spec.needles:
        when = place_needle(at(workday(POOL_DAY_1, day), hhmm), sessions)
        sessions.append([Turn(when, text)])
    probes = [
        Turn(at(probe_day, p.time), p.text, {"should": p.should, "should_not": p.should_not}) for p in spec.probes
    ]
    sessions.append(probes)
    sessions.sort(key=lambda session: session[0].when)
    events = lay_out(sessions, first_number=1, width=3)
    return events, largest_move(sessions, events)


def probe_session_start(events: list[dict]) -> int:
    """Index of the start event of the session that holds the first probe."""
    probe = next(e for e in events if e["type"] == "probe")
    return next(i for i, e in enumerate(events) if e.get("session") == probe["session"])


def build_sweep(size: int, base_lines: list[str], pool: list[dict]) -> tuple[list[str], int]:
    """Lines of sweep_<size> and the largest move: sweep_40 byte for byte up to its probe
    session, then pool messages 1..size-40 as sessions from the next workday (ids continue
    after sweep_40's), then sweep_40's probe session, unchanged except for its date and id,
    on the next workday after that."""
    if size - SWEEP_BASE > len(pool):
        raise ValueError(f"sweep_{size} needs {size - SWEEP_BASE} pool messages; the pool has {len(pool)}")
    base = [json.loads(line) for line in base_lines]
    cut = probe_session_start(base)
    kept = base[:cut]
    last_day = max(datetime.fromisoformat(e["ts"]).date() for e in kept if "ts" in e)
    turns = pool_turns(pool[: size - SWEEP_BASE], next_workday(last_day))
    sessions = group_sessions(turns)
    first_number = 1 + max(int(e["session"][1:]) for e in kept if "session" in e)
    lines = base_lines[:cut]
    if kept[-1]["type"] != "restart":
        lines.append(to_line({"type": "restart"}))
    appended = lay_out(sessions, first_number, width=2)
    lines += [to_line(e) for e in appended]
    lines.append(to_line({"type": "restart"}))
    probe_day = next_workday(turns[-1].when.date())
    probe_id = f"s{first_number + len(sessions):02d}"
    for e in base[cut:]:
        moved_ts = datetime.combine(probe_day, datetime.fromisoformat(e["ts"]).time())
        lines.append(to_line(dict(e, session=probe_id, ts=moved_ts.isoformat(timespec="seconds"))))
    return lines, largest_move(sessions, appended)


# ---------------------------------------------------------------- b0's window, estimated


def mean_reply_tokens(root: Path, counter: TokenCounter) -> tuple[float, int]:
    """Mean tokens of the replies b0 really sent in the baseline run, and how many there were."""
    sizes: list[int] = []
    for path in sorted((root / B0_EVENTS).glob("b0__*.jsonl")):
        for row in read_jsonl(path):
            if row.get("type") in ("msg", "probe") and row.get("reply"):
                sizes.append(counter.count_text(row["reply"]))
    if not sizes:
        return FALLBACK_REPLY_TOKENS, 0
    return sum(sizes) / len(sizes), len(sizes)


def b0_probe_input_tokens(root: Path, stem: str) -> int | None:
    """input_tokens of b0's first probe reply on `stem` in the baseline run (None if it never ran)."""
    path = root / B0_EVENTS / f"b0__{stem}__r0.jsonl"
    if not path.exists():
        return None
    return next((row["input_tokens"] for row in read_jsonl(path) if row.get("type") == "probe"), None)


def as_b0_sends(e: dict) -> str:
    """A user turn as b0 puts it in the prompt: prefixed with the time it was sent."""
    return f"[{dt_label(e['ts'])}] {e['text']}"


@dataclass
class B0Window:
    """A model of b0's prompt, to estimate whether a probe's needle is still inside it.

    b0 sends its system prompt, then the newest earlier messages that fit within
    target_input_tokens (7,400), then the probe. So the needle is in its prompt only if
    everything from the needle message up to the probe fits next to the other two.
    """

    counter: TokenCounter
    reply_tokens: float  # the mean size of b0's real replies
    persona: str

    def reach(self, events: list[dict], probe_index: int, phrases) -> dict | None:
        """Tokens from the needle message (the first turn holding a needle phrase) up to
        the probe, and the budget they must fit in. User turns are counted exactly as b0
        sends them, time stamp included; every turn gets one reply of the mean size; every
        pair adds 14 tokens of chat template. None when the probe has no needle phrase."""
        turns = [e for e in events if e["type"] in ("msg", "probe")]
        probe_at = [i for i, e in enumerate(turns) if e["type"] == "probe"][probe_index]
        carriers = [i for i in range(probe_at) if any(p.lower() in turns[i]["text"].lower() for p in phrases)]
        if not carriers:
            return None
        history = turns[carriers[0] : probe_at]
        per_pair = self.reply_tokens + 2 * PER_MESSAGE_TOKENS
        tokens = round(sum(self.counter.count_text(as_b0_sends(e)) + per_pair for e in history))
        probe = turns[probe_at]
        system = self.persona + "\n\n" + TIME_NOTE + "\n" + header(datetime.fromisoformat(probe["ts"]))
        fixed = (
            self.counter.count_text(system) + self.counter.count_text(as_b0_sends(probe))
            + 2 * PER_MESSAGE_TOKENS + PER_PROMPT_TOKENS
        )
        budget = DEFAULTS["target_input_tokens"] - fixed
        return {
            "needle_ts": history[0]["ts"], "pairs": len(history), "tokens": tokens,
            "budget": budget, "prompt": tokens + fixed, "outside": tokens > budget,
        }


def describe_reach(index: int, reach: dict | None, bold: bool = False) -> str:
    """One probe's estimated b0 reach in words."""
    if reach is None:
        return f"#{index}: no needle (abstention probe)"
    verdict = "outside" if reach["outside"] else "inside"
    if bold:
        verdict = f"**{verdict}**"
    return (
        f"#{index}: needle {dt_label(reach['needle_ts'])}, {reach['pairs']} message pairs back, "
        f"~{reach['tokens']:,} tokens vs a {reach['budget']:,}-token budget: {verdict} "
        f"({reach['tokens'] / reach['budget']:.1f}x)"
    )


# ---------------------------------------------------------------- shared files


def update_needles(text: str, entries: dict[str, list[str]]) -> str:
    """needles.json with this generator's keys replaced and everyone else's kept."""
    needles = {key: value for key, value in json.loads(text).items() if key.rsplit("#", 1)[0] not in own_stems()}
    needles.update(entries)
    return json.dumps(needles, ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def update_audit(text: str, controls: list[dict]) -> str:
    """audit_controls.jsonl with this generator's rows replaced; other lines kept as they are."""
    others = [line for line in text.split("\n") if line.strip() and json.loads(line)["scenario"] not in own_stems()]
    return "".join(line + "\n" for line in others + [to_line(row) for row in controls])


def update_index(text: str, section: str) -> str:
    """INDEX.md with this generator's section replaced, or appended if it is not there yet.
    The section runs from its heading to the next "# " or "## " heading."""
    head, found, rest = text.partition(INDEX_HEADING + "\n")
    tail = ""
    if found:
        following = re.search(r"^#{1,2} ", rest, flags=re.MULTILINE)
        tail = rest[following.start() :] if following else ""
    else:
        head = text
    return head.rstrip("\n") + "\n\n" + section.rstrip("\n") + "\n" + ("\n" + tail if tail else "")


def cell(text: str) -> str:
    """Text safe inside a markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def describe_probes(probes: tuple[Probe, ...]) -> str:
    parts = [f'"{p.text}" Pass = {p.should}. Fail = {p.should_not}.' for p in probes]
    if len(parts) > 1:
        parts = [f"({i}) {part}" for i, part in enumerate(parts, start=1)]
    return f"{len(probes)}: " + " ".join(parts)


def index_section(rows: list[dict], facts: dict) -> str:
    """The INDEX.md section: why these files exist, how they are built, one row per file."""
    reply = facts["reply_tokens"]
    budgets = sorted({r["budget"] for row in rows for r in row["reach"] if r})
    budget_text = f"{budgets[0]:,}" if len(budgets) == 1 else f"{budgets[0]:,}-{budgets[-1]:,}"
    if facts["sweep40_measured"] is not None:
        error = facts["sweep40_estimate"] / facts["sweep40_measured"] - 1
        smallest = min(r["tokens"] / r["budget"] for row in rows for r in row["reach"] if r)
        calibration = (
            f"With replies that short, b0's prompt at the sweep_40 probe was only {facts['sweep40_measured']:,} "
            "tokens, so the whole history fits and b0 sees the needle. (The estimate below gives "
            f"{facts['sweep40_estimate']:,} for that prompt, {error:+.0%}; every file below needs at least "
            f"{smallest:.1f}x b0's budget, a far wider margin than that error.)"
        )
    else:
        calibration = "With replies that short, even sweep_40's whole history fits and b0 sees the needle."
    lines = [
        INDEX_HEADING,
        "",
        "**Why these exist.** Almost every hand-written scenario fits inside b0's recency window "
        "(own_02's 13k-token paste is the exception), so none of them can show "
        "the brief's \"gets less useful the more they use it\". b0's real replies are short: the "
        f"{facts['replies']:,} b0 replies in `results/runs/baseline` average {reply:.1f} tokens, far below the "
        f"450-700 tokens per draft that the pre-run estimates above assumed. {calibration} These files replay six "
        "weeks of daily use, so the fact a probe needs ends up far outside the window.",
        "",
        "**How they are built** (`python -m eval.longgen`; no randomness, so re-running rewrites the same bytes):",
        f"- Source: the message pool in `long/_pool/`: {facts['pool']} messages on {facts['accounts']} "
        f"accounts over workdays {facts['days']} ({facts['first_date']} to {facts['last_date']}), about "
        f"{facts['per_day']:.0f} a day ({facts['kinds']}). `long_04` uses `heavy_day.json` alone "
        f"({facts['heavy']} messages on {day_label(HEAVY_DAY)}).",
        "- Sessions: within a day, a message joins the current session while it comes at most 25 minutes "
        "after the previous one and the session has fewer than 4 messages. `start` is 1 minute before the "
        "first message and `end` 2 minutes after the last; every 4th session has no `end` (the tab was "
        "closed). A `restart` separates days. Time only moves forward: an event that would not come after "
        "the previous one moves to one minute after it, so a few messages are sent a minute or two after "
        f"their pool time (at most {facts['moved']} minutes; see the last column of the stats table).",
        "- Needles are their own sessions at their stated day and time, moved 5 minutes later until they "
        f"overlap no pool session. The probes come in one session on {day_label(PROBE_DAY)}, after a restart "
        "(`long_04`: 18:05 the same day).",
        "- The pool never mentions a planted account or person (`eval/longgen.py` checks this on every "
        "run), so each probe has one right answer.",
        "- Sweeps: `sweep_080/160/320` keep sweep_40 byte for byte up to its probe session, append the first "
        "40/120/280 pool messages from the next workday (session ids continue from s22), then repeat "
        "sweep_40's probe session (same text and expect) on the next workday at 15:01. The pool's texts keep "
        "their own Feb-Mar dates, and some of its accounts (Contoso, Northwind, Tailspin, ...) also appear in "
        "sweep_40 with other contacts. As filler that is harmless: the probe is about Fabrikam, which the "
        "pool never mentions.",
        "",
        "**b0 reach** = the tokens b0 would have to carry from the needle message up to the probe: user turns "
        "exactly as b0 sends them (with its time stamp; Qwen3 tokenizer), plus "
        f"{reply:.1f} tokens per reply (the measured mean) and 14 tokens of chat template per message pair. "
        "The budget is b0's 7,400-token target minus its system prompt, the probe and 10 tokens of prompt "
        f"overhead ({budget_text} here). Outside = the needle cannot be in b0's prompt. At this pool's average "
        f"of {facts['pair_tokens']:.0f} tokens per message pair, the budget holds about {facts['fit_pairs']} "
        f"pairs, about {facts['fit_days']:.1f} workdays of the pool. These are estimates; the eval's "
        "`needle_hits` (in each probe row of the events) measures the real reach.",
        "",
        "| file | purpose | complaint | probes | events / msgs | b0 reach (estimated) |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        reach = "; ".join(describe_reach(i, r, bold=True) for i, r in enumerate(row["reach"]))
        stats = row["stats"]
        lines.append(
            f"| `{row['name']}` | {cell(row['purpose'])} | {row['complaint']} | {cell(row['probes'])} | "
            f"{stats['events']:,} / {stats['msgs']} | {reach} |"
        )
    lines += [
        "",
        "| file | events | msgs | probes | sessions | no `end` | restarts | user tokens (Qwen3, incl. probes) "
        "| largest move (min) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        s = row["stats"]
        lines.append(
            f"| {Path(row['name']).stem} | {s['events']:,} | {s['msgs']} | {s['probes']} | {s['sessions']} | "
            f"{s['no_end']} | {s['restarts']} | {s['user_tokens']:,} | {s['moved']} |"
        )
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- putting it together


def file_stats(events: list[dict], counter: TokenCounter, moved: int) -> dict:
    """The linter's counts, plus sessions without an end, the user tokens (Qwen3) and the
    largest move the layout made."""
    stats = counts(events)
    started = {e["session"] for e in events if e["type"] == "start"}
    ended = {e["session"] for e in events if e["type"] == "end"}
    stats["no_end"] = len(started - ended)
    stats["user_tokens"] = sum(counter.count_text(e["text"]) for e in events if e["type"] in ("msg", "probe"))
    stats["moved"] = moved
    return stats


def render_all(root: Path = ROOT) -> tuple[dict[Path, str], list[dict], dict]:
    """Every file this generator writes (repository-relative path -> full text), one row of
    stats per scenario file, and the facts quoted in INDEX.md. Reads files; writes none."""
    pool = load_pool(root)
    check_pool(pool)
    heavy = load_heavy_day(root)
    counter = TokenCounter(MODEL)
    reply_tokens, replies = mean_reply_tokens(root, counter)
    window = B0Window(counter, reply_tokens, (PROMPTS_DIR / "persona.txt").read_text(encoding="utf-8").strip())
    needles_text, needles_newline = read_text(root / NEEDLES_FILE)
    audit_text, audit_newline = read_text(root / AUDIT_FILE)
    index_text, index_newline = read_text(root / INDEX_FILE)
    sweep40_needles = json.loads(needles_text)["sweep_40#0"]
    sweep40_audit = next(json.loads(line) for line in audit_text.split("\n")
                         if line.strip() and json.loads(line)["scenario"] == "sweep_40")
    base_lines = (root / SWEEP_DIR / "sweep_40.jsonl").read_text(encoding="utf-8").split("\n")[:-1]
    sweep40_events = [json.loads(line) for line in base_lines]
    cut = probe_session_start(sweep40_events)

    outputs: dict[Path, str] = {}
    needles: dict[str, list[str]] = {}
    controls: list[dict] = []
    rows: list[dict] = []
    for spec in LONG_SCENARIOS:
        events, moved = build_long(spec, pool, heavy)
        path = LONG_DIR / f"{spec.stem}.jsonl"
        outputs[path] = "".join(to_line(e) + "\n" for e in events)
        for i, probe in enumerate(spec.probes):
            needles[f"{spec.stem}#{i}"] = list(probe.needles)
            controls.append({"scenario": spec.stem, "probe_index": i, "gold": probe.gold, "wrong": probe.wrong})
        rows.append({
            "name": path.relative_to("scenarios").as_posix(), "purpose": spec.purpose,
            "complaint": spec.complaint, "probes": describe_probes(spec.probes),
            "stats": file_stats(events, counter, moved),
            "reach": [window.reach(events, i, p.needles) for i, p in enumerate(spec.probes)],
        })
    for size in SWEEP_SIZES:
        stem = sweep_stem(size)
        lines, moved = build_sweep(size, base_lines, pool)
        events = [json.loads(line) for line in lines]
        path = SWEEP_DIR / f"{stem}.jsonl"
        outputs[path] = "".join(line + "\n" for line in lines)
        needles[f"{stem}#0"] = list(sweep40_needles)
        controls.append(
            {"scenario": stem, "probe_index": 0, "gold": sweep40_audit["gold"], "wrong": sweep40_audit["wrong"]}
        )
        probe_text = next(e["text"] for e in events if e["type"] == "probe")
        rows.append({
            "name": path.relative_to("scenarios").as_posix(), "purpose": sweep_purpose(size, events, cut),
            "complaint": "1, 3", "probes": f'1: "{probe_text}" (sweep_40\'s probe, same expect)',
            "stats": file_stats(events, counter, moved), "reach": [window.reach(events, 0, sweep40_needles)],
        })

    pool_pairs = [
        counter.count_text(f"[{dt_label(t.when)}] {t.text}") + reply_tokens + 2 * PER_MESSAGE_TOKENS
        for t in pool_turns(pool, POOL_DAY_1)
    ]
    days = sorted({m["day"] for m in pool})
    budget = min(r["budget"] for row in rows for r in row["reach"] if r)
    pair_tokens = sum(pool_pairs) / len(pool_pairs)
    facts = {
        "reply_tokens": reply_tokens, "replies": replies, "pool": len(pool),
        "accounts": len({m["account"] for m in pool}), "days": f"{days[0]}-{days[-1]}",
        "first_date": day_label(workday(POOL_DAY_1, days[0])), "last_date": day_label(workday(POOL_DAY_1, days[-1])),
        "per_day": len(pool) / len(days), "heavy": len(heavy),
        "kinds": ", ".join(f"{n} {kind}" for kind, n in sorted(Counter(m["kind"] for m in pool).items())),
        "pair_tokens": pair_tokens, "fit_pairs": int(budget // pair_tokens),
        "fit_days": (budget // pair_tokens) / (len(pool) / len(days)),
        "sweep40_measured": b0_probe_input_tokens(root, "sweep_40"),
        "sweep40_estimate": window.reach(sweep40_events, 0, sweep40_needles)["prompt"],
        "moved": max(row["stats"]["moved"] for row in rows),
    }
    outputs[NEEDLES_FILE] = update_needles(needles_text, needles).replace("\n", needles_newline)
    outputs[AUDIT_FILE] = update_audit(audit_text, controls).replace("\n", audit_newline)
    outputs[INDEX_FILE] = update_index(index_text, index_section(rows, facts)).replace("\n", index_newline)
    return outputs, rows, facts


def sweep_purpose(size: int, events: list[dict], cut: int) -> str:
    """The INDEX.md purpose of one sweep file, read off its events (`cut` is the number of
    events kept from sweep_40)."""
    added = events[cut : probe_session_start(events)]
    sessions = sum(1 for e in added if e["type"] == "start")
    dates = sorted({e["ts"][:10] for e in added if e["type"] == "msg"})
    kept_msgs = sum(1 for e in events[:cut] if e["type"] == "msg")
    probe = next(e for e in events if e["type"] == "probe")
    return (
        f"Window sweep, N = {size}: sweep_40 byte for byte up to its probe session ({kept_msgs} messages), then "
        f"pool messages 1-{size - SWEEP_BASE} as {sessions} sessions on {len(dates)} workdays "
        f"({day_label(dates[0])} to {day_label(dates[-1])}), then sweep_40's probe session on "
        f"{day_label(probe['ts'])} at {probe['ts'][11:16]}."
    )


def main(argv: list[str] | None = None) -> int:
    """Write every output file (under --out instead of the repository, if given), print the
    stats per file, then lint the scenario files; exit status 1 if the linter complains."""
    console_safe()
    parser = argparse.ArgumentParser(prog="python -m eval.longgen", description=__doc__.split("\n")[0])
    parser.add_argument("--out", help="write under this directory instead of the repository (the tests use it)")
    args = parser.parse_args(argv)
    out = Path(args.out).resolve() if args.out else ROOT
    outputs, rows, facts = render_all(ROOT)
    for path, text in outputs.items():
        write_text(out / path, text)
    print(
        f"b0 replies: mean {facts['reply_tokens']:.1f} tokens over {facts['replies']} replies "
        f"in {B0_EVENTS.as_posix()}"
    )
    if facts["sweep40_measured"] is not None:
        print(f"estimate check, sweep_40 probe: {facts['sweep40_estimate']:,} estimated vs "
              f"{facts['sweep40_measured']:,} measured b0 input tokens")
    for row in rows:
        s = row["stats"]
        print(
            f"scenarios/{row['name']}: {s['events']:,} events, {s['msgs']} msgs, {s['probes']} probes, "
            f"{s['sessions']} sessions ({s['no_end']} without end), {s['restarts']} restarts, "
            f"{s['user_tokens']:,} user tokens, largest move {s['moved']} min"
        )
        for i, reach in enumerate(row["reach"]):
            print("  " + describe_reach(i, reach))
    print(f"wrote {len(outputs)} files under {out.as_posix()}")
    problems = []
    for path in scenario_paths():
        problems += [f"{path.as_posix()}: {p}" for p in check(out / path)[1]]
    for problem in problems:
        print(problem)
    print(f"lint: {len(scenario_paths())} scenario files, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
